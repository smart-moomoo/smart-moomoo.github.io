  // Draws sprite `name` into a 2D canvas context, `size` px per grid cell.
  function draw(ctx, name, palette, size, dx, dy) {
    const rows = SPRITES[name];
    if (!rows) return;
    dx = dx || 0; dy = dy || 0;
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      for (let x = 0; x < row.length; x++) {
        const ch = row[x];
        if (ch === '.') continue;
        const color = palette[ch];
        if (!color) continue;
        ctx.fillStyle = color;
        ctx.fillRect(dx + x * size, dy + y * size, size, size);
      }
    }
  }

  // Creates a crisp canvas sized for GRID*size px, DPR-aware so it stays
  // sharp on retina screens without any blur.
  function createCanvas(size) {
    const dpr = window.devicePixelRatio || 1;
    const canvas = document.createElement('canvas');
    const display = GRID * size;
    canvas.width = Math.round(display * dpr);
    canvas.height = Math.round(display * dpr);
    canvas.style.width = display + 'px';
    canvas.style.height = display + 'px';
    const ctx = canvas.getContext('2d');
    ctx.scale(dpr, dpr);
    ctx.imageSmoothingEnabled = false;
    return canvas;
  }

  return { GRID, PLANT_PALETTE, ANIMAL_PALETTE, MISC_PALETTE, PEOPLE_PALETTE, SPRITES, draw, createCanvas };
